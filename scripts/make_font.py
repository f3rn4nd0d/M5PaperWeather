#!/usr/bin/env python3
"""Generate weather/Font.h: Inter (SIL OFL) rendered as 4-bit anti-aliased glyph bitmaps.

The M5Paper has no system fonts, so every size/weight used by the display is pre-rendered here.
Output per font: a table of glyphs (bounding box, bearings, advance) plus one byte per pixel
(0 = white ... 15 = black).  Drawn by WeatherDisplay::DrawText().   Needs Pillow.

  python3 scripts/make_font.py
"""
import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
TTF = os.path.join(HERE, "fonts", "Inter-Variable.ttf")
OUT = os.path.join(HERE, "..", "weather", "Font.h")

TEXT = "".join(chr(c) for c in range(32, 127)) + "°·–áéíóúüñÁÉÍÓÚÑ¿¡"
DIGITS = "0123456789-°"

# name, em size in px, weight, optical size, characters
FONTS = [
    ("HERO",  188, 230, 32, DIGITS),   # the big temperature
    ("TITLE",  38, 600, 32, TEXT),     # tile values
    ("BODY",   26, 450, 20, TEXT),     # secondary lines
    ("CAP",    19, 520, 14, TEXT),     # captions
    ("TINY",   15, 560, 14, TEXT),     # graph axes
    ("XTITLE", 48, 600, 32, TEXT),     # big tile values (top half)
    ("XBODY",  28, 450, 20, TEXT),     # big secondary lines (top half)
    ("XCAP",   22, 520, 14, TEXT),     # big units (top half)
]


def build(name, size, wght, opsz, chars):
    f = ImageFont.truetype(TTF, size)
    f.set_variation_by_axes([opsz, wght])
    asc, desc = f.getmetrics()
    glyphs, blob = [], []
    for ch in chars:
        adv = round(f.getlength(ch))
        l, t, r, b = f.getbbox(ch, anchor="ls")           # relative to baseline origin
        if r <= l or b <= t:                              # space
            glyphs.append((ord(ch), len(blob), 0, 0, 0, 0, adv))
            continue
        w, h = r - l, b - t
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-l, -t), ch, font=f, fill=255, anchor="ls")
        data = img.tobytes()
        ink = [min(15, round((v / 255.0) ** 0.85 * 15)) for v in data]
        glyphs.append((ord(ch), len(blob), w, h, l, t, adv))
        blob.extend(ink)
    return asc, desc, glyphs, blob


def main():
    out = ["// Generated by scripts/make_font.py from Inter (SIL OFL 1.1, scripts/fonts/OFL-Inter.txt).",
           "// Do not edit by hand.", "#pragma once", "#include <stdint.h>", "",
           "struct GlyphInfo { uint16_t cp; uint32_t off; uint8_t w, h; int8_t xo; int16_t yo; uint8_t adv; };",
           "struct FontInfo  { const GlyphInfo *glyphs; const uint8_t *bits; uint16_t count; uint8_t ascent; uint8_t height; };", ""]
    for name, size, wght, opsz, chars in FONTS:
        asc, desc, glyphs, blob = build(name, size, wght, opsz, chars)
        out.append("static const GlyphInfo FONT_%s_GLYPHS[] = {" % name)
        out.extend("   {%d,%d,%d,%d,%d,%d,%d}," % g for g in glyphs)
        out.append("};")
        out.append("static const uint8_t FONT_%s_BITS[] = {" % name)
        for i in range(0, len(blob), 64):
            out.append("   " + ",".join(map(str, blob[i:i + 64])) + ",")
        out.append("   0};")
        out.append("static const FontInfo FONT_%s = {FONT_%s_GLYPHS, FONT_%s_BITS, %d, %d, %d};\n"
                   % (name, name, name, len(glyphs), asc, asc + desc))
        print("%-5s %3dpx w%d: %3d glyphs, %6d px" % (name, size, wght, len(glyphs), len(blob)))
    with open(OUT, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote", os.path.normpath(OUT), os.path.getsize(OUT) // 1024, "KB")


if __name__ == "__main__":
    main()

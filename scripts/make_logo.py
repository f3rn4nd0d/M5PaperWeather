#!/usr/bin/env python3
"""Generate weather/Logo.h (the Casa Grajera logo for the M5Paper header).

Default: the words "Casa Grajera" written with the Borel font (SIL OFL, scripts/fonts).
With --image you can use your real logo (PNG/SVG-exported PNG, dark on light or with alpha).

Output: 4-bit ink levels, one byte per pixel (0 = white, 15 = black), drawn by
WeatherDisplay::DrawLogo().  Needs Pillow:  pip install pillow

Examples:
  python3 scripts/make_logo.py
  python3 scripts/make_logo.py --text "Casa Grajera" --height 30
  python3 scripts/make_logo.py --image mi_logo.png --height 30
"""
import argparse, os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))


def render_text(text, font_path, height):
    scale = 4                                   # supersampling for smooth edges
    size = int(height * 1.15) * scale
    font = ImageFont.truetype(font_path, size)
    l, t, r, b = font.getbbox(text)
    img = Image.new("L", (r - l + 8 * scale, b - t + 8 * scale), 255)
    ImageDraw.Draw(img).text((4 * scale - l, 4 * scale - t), text, font=font, fill=0)
    return img


def render_image(path):
    img = Image.open(path).convert("RGBA")
    bg = Image.new("RGBA", img.size, (255, 255, 255, 255))
    return Image.alpha_composite(bg, img).convert("L")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--text", default="Casa Grajera")
    ap.add_argument("--font", default=os.path.join(HERE, "fonts", "Borel-Regular.ttf"))
    ap.add_argument("--image", help="use this image instead of the text")
    ap.add_argument("--height", type=int, default=30, help="logo height in pixels (header is 34 px)")
    ap.add_argument("--out", default=os.path.join(HERE, "..", "weather", "Logo.h"))
    ap.add_argument("--prefix", default="LOGO", help="prefix of the _W/_H defines")
    ap.add_argument("--symbol", default="LOGO_CASA_GRAJERA", help="name of the pixel array")
    ap.add_argument("--solid", action="store_true", help="stretch contrast so a coloured logo prints black")
    ap.add_argument("--preview", help="optional PNG preview of the result")
    a = ap.parse_args()

    img = render_image(a.image) if a.image else render_text(a.text, a.font, a.height)
    if a.solid:                                                # coloured mark -> full black on e-ink
        lo = img.getextrema()[0]
        img = img.point(lambda p: 255 - min(255, (255 - p) * 255 // max(1, 255 - lo)))
    bbox = Image.eval(img, lambda p: 255 - p).getbbox()        # crop empty borders
    if bbox:
        img = img.crop(bbox)
    w = max(1, round(img.width * a.height / img.height))
    img = img.resize((w, a.height), Image.LANCZOS)

    ink = [15 - (p * 15 + 127) // 255 for p in img.tobytes()]  # 0..15, 15 = black
    if a.preview:
        Image.frombytes("L", img.size, bytes(255 - i * 17 for i in ink)).save(a.preview)

    lines = []
    for y in range(a.height):
        row = ink[y * w:(y + 1) * w]
        lines.append("   " + ",".join("%d" % v for v in row) + ",")
    src = a.image if a.image else '"%s" in Borel' % a.text
    with open(a.out, "w") as f:
        f.write("// Generated by scripts/make_logo.py from %s. Do not edit by hand.\n" % src)
        f.write("// Borel font by Rosalie Wagner, SIL Open Font License 1.1 (see scripts/fonts/OFL.txt).\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("#define %s_W %d\n#define %s_H %d\n\n" % (a.prefix, w, a.prefix, a.height))
        f.write("// ink level per pixel: 0 = white ... 15 = black\n")
        f.write("static const uint8_t %s[%s_W * %s_H] = {\n" % (a.symbol, a.prefix, a.prefix))
        f.write("\n".join(lines) + "\n};\n")
    print("wrote %s (%dx%d)" % (os.path.normpath(a.out), w, a.height))


if __name__ == "__main__":
    main()
